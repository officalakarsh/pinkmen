import { JewelleryItem, Currency } from '../types';

export const CURRENCY_RATES: Record<Currency, { symbol: string; rate: number; label: string }> = {
  INR: { symbol: '₹', rate: 1, label: 'INR (₹)' },
  USD: { symbol: '$', rate: 0.012, label: 'USD ($)' },
  GBP: { symbol: '£', rate: 0.0095, label: 'GBP (£)' },
  AED: { symbol: 'AED ', rate: 0.044, label: 'AED (د.إ)' },
};

export function formatPrice(amountINR: number, currency: Currency): string {
  const info = CURRENCY_RATES[currency];
  const converted = amountINR * info.rate;

  if (currency === 'INR') {
    return `${info.symbol}${amountINR.toLocaleString('en-IN')}`;
  }
  return `${info.symbol}${Math.round(converted).toLocaleString('en-US')}`;
}

